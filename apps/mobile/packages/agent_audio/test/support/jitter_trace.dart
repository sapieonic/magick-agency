import 'dart:typed_data';

import 'package:agent_audio/reference.dart';

/// Generates the cross-language jitter-buffer trace (`test/fixtures/jitter_trace.txt`).
///
/// The scenario models what a TCP media path does to 20 ms frames: an initial gap, steady
/// flow, stalls followed by bursts (short and long enough to overflow), random stall/burst
/// traffic, then a long steady stretch so the target shrinks. Each `pop` line records the
/// output kind and a position-weighted checksum of the samples; `stats` lines record the
/// counters. The Kotlin port replays the file (`JitterBufferTraceTest.kt`); the Swift port
/// follows the same file format for when it can be tested on macOS.
///
/// Format, one op per line:
///
/// ```text
/// config <frameSamples> <minTarget> <maxTarget> <initialTarget> <capacity> <growStep>
///        <shrinkAfter> <trimSlack> <trimAfter> <concealFrames>
/// push <seed>                  frame sample j = ((seed * 7919 + j * 104729) % 65536) - 32768
/// pop <real|concealed|silence> <checksum>   checksum = Σ out[j] * (j + 1)
/// stats <depth> <target> <underruns> <concealed> <silent> <overflowDrops> <latencyDrops>
///       <received> <played>
/// ```
String generateJitterTrace() {
  // Shrinks after 100 frames instead of 500 so the trace reaches the minimum target in a
  // reasonable length; the config line carries it, so the ports replay the same tuning.
  const config = JitterBufferConfig(frameSamples: 16, shrinkAfterFrames: 100);
  final jb = JitterBuffer(config);
  final out = StringBuffer()
    ..writeln('# Generated by test/support/jitter_trace.dart from lib/src/jitter/jitter_buffer.dart.')
    ..writeln('# Regenerate: UPDATE_JITTER_TRACE=1 flutter test test/jitter_buffer_test.dart')
    ..writeln('config ${config.frameSamples} ${config.minTargetFrames} ${config.maxTargetFrames} '
        '${config.initialTargetFrames} ${config.capacityFrames} ${config.growStepFrames} '
        '${config.shrinkAfterFrames} ${config.trimSlackFrames} ${config.trimAfterFrames} ${config.concealFrames}');

  final frame = Int16List(config.frameSamples);
  final pcm = Int16List(config.frameSamples);
  var seed = 0;
  var ops = 0;

  void stats() => out.writeln(jb.snapshot.toTraceLine());

  void tickStats() {
    ops++;
    if (ops % 50 == 0) stats();
  }

  void push() {
    seed++;
    fillTraceFrame(frame, seed);
    jb.push(frame);
    out.writeln('push $seed');
    tickStats();
  }

  void pop() {
    final kind = jb.pop(pcm);
    out.writeln('pop ${kind.name} ${traceChecksum(pcm, config.frameSamples)}');
    tickStats();
  }

  // 1. Nothing has arrived yet.
  for (var i = 0; i < 10; i++) {
    pop();
  }
  // 2. Steady flow.
  for (var i = 0; i < 200; i++) {
    push();
    pop();
  }
  stats();
  // 3. A 160 ms stall, then the backlog arrives at once.
  for (var i = 0; i < 8; i++) {
    pop();
  }
  for (var i = 0; i < 8; i++) {
    push();
  }
  for (var i = 0; i < 100; i++) {
    push();
    pop();
  }
  stats();
  // 4. A 1 s stall, then a 40-frame burst: overflow, then latency trimming.
  for (var i = 0; i < 50; i++) {
    pop();
  }
  for (var i = 0; i < 40; i++) {
    push();
  }
  for (var i = 0; i < 200; i++) {
    push();
    pop();
  }
  stats();
  // 5. Random stalls and bursts (deterministic LCG).
  var rng = 12345;
  int next() {
    rng = (rng * 1103515245 + 12345) & 0x7fffffff;
    return rng >> 8;
  }

  var stallLeft = 0;
  var owed = 0;
  for (var i = 0; i < 1500; i++) {
    if (stallLeft > 0) {
      stallLeft--;
      owed++;
    } else if (next() % 100 < 3) {
      stallLeft = 4 + next() % 20;
      owed++;
    } else {
      for (var k = 0; k <= owed; k++) {
        push();
      }
      owed = 0;
    }
    pop();
  }
  stats();
  // 6. Long steady stretch: the target shrinks back toward the minimum.
  for (var i = 0; i < 1200; i++) {
    push();
    pop();
  }
  stats();
  return out.toString();
}

void fillTraceFrame(Int16List frame, int seed) {
  for (var j = 0; j < frame.length; j++) {
    frame[j] = ((seed * 7919 + j * 104729) % 65536) - 32768;
  }
}

int traceChecksum(Int16List pcm, int n) {
  var sum = 0;
  for (var j = 0; j < n; j++) {
    sum += pcm[j] * (j + 1);
  }
  return sum;
}
